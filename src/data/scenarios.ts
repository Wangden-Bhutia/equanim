import type { DomainId } from '../types';

export type Setting = 'Work' | 'Family' | 'Friendship' | 'Partner' | 'Self' | 'Online' | 'Public' | 'Home';

export interface ScenarioOption {
  id: string;
  text: string;
  /** A neutral name for the pattern the choice reflects. Never a grade. */
  pattern: string;
  feedback: {
    /** What this response tends to do in the moment. */
    what: string;
    /** What it may accomplish or protect. */
    protects: string;
    /** Its risks, and the assumptions it rests on. */
    costs: string;
    /** A practical question or next step to end on. */
    notice: string;
    /** Another response worth considering, where useful. */
    alternative?: string;
  };
}

export interface Scenario {
  id: string;
  domain: DomainId;
  setting: Setting;
  title: string;
  situation: string;
  prompt: string;
  options: ScenarioOption[];
  /** Short reasoning: why this situation is worth practising and what it shows. */
  insight: string;
  reflection: string;
  /** Coverage themes from the specification. */
  themes: ThemeId[];
}

